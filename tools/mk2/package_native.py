"""Build/install the authenticated standalone MK2 native package and collection launcher."""
from pathlib import Path
import argparse,hashlib,json,os,shlex,shutil,sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]))
from tools.mk2 import run,profile
from tools.quality import run as q
from tools.launcher_backend_build import arguments
ROOT=q.ROOT
SOURCES=[p for p in run.SOURCES if p!='native/tests/mk2_foundation_tests.cpp']+[
    'native/mk2/mk2_native_check.cpp','native/mk2/mk2_music.cpp','native/src/mk5_window.cpp','native/src/mk5_audio_output.cpp']
FLAGS=['-std=c++17','-O2','-Wall','-Wextra','-Werror','-Wno-unused-parameter',
       '-Wno-missing-field-initializers','-pthread','-municode','-Inative/include']
LIBRARIES=['-l'+n for n in ('bcrypt','user32','gdi32','winmm','d3d12','dxgi','d3dcompiler','dxguid','windowscodecs','ole32','uuid')]

def unlinked(path):
    for p in (path,*path.parents):
        if p.is_symlink() or p.is_junction():raise ValueError('Linked package path: '+str(p))

def digest(rows):return hashlib.sha256(json.dumps(rows,sort_keys=True,separators=(',',':')).encode()).hexdigest()

def identities(scratch,env):
    files={}
    result=q.command([q.DEFAULT_CC,*FLAGS,'-MM','-MT','mk2-dependencies',*SOURCES],
                     scratch,cwd=ROOT,env=env,timeout=30,output_limit=4*1024*1024)
    if not result['passed'] or result['discarded_output_bytes']:
        raise RuntimeError('Incomplete compiler dependencies: '+result['stdout'][-4000:])
    # Every input emits the same target; shlex retains make-escaped spaces.
    tokens=shlex.split(result['stdout'].replace('\\\r\n',' ').replace('\\\n',' '))
    from tools.setup.paths import generated_sources   # the first-fight pages, compiled as their own units
    if tokens.count('mk2-dependencies:')!=len(SOURCES)+len(generated_sources([ROOT/p for p in SOURCES])):
        raise RuntimeError('Missing compiler dependency rule')
    for name in tokens:
        if name=='mk2-dependencies:':continue
        path=(ROOT/name).resolve();relative=path.relative_to(ROOT).as_posix()
        # includes generated by the setup keep the name they had in the source tree (the launcher pins stay comparable)
        if relative.startswith('generated/mk2/'):relative='native/mk2/'+path.name
        files[relative]=q.sha(path)
    overlays={p:h for p,h in files.items()if p.endswith('.inc')}
    return dict(source_sha256=files['native/mk2/mk2_native_check.cpp'],runtime_sources_sha256=digest(files),
                core_overlays_sha256=digest(overlays),files=files)

def main(installation_root=ROOT):
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--inspect',action='store_true');args=parser.parse_args()
    stage=installation_root/'build/native/mk2-native-v1'
    r={'passed':False,'full_arcade_fidelity_certified':False}
    try:
        unlinked(stage);stage.mkdir(parents=True,exist_ok=True)
        with q.scratch_tree()as(scratch,cleanup):
            r['cleanup']=cleanup
            env={'PATH':str(q.DEFAULT_CC.parent)+os.pathsep+os.environ['PATH'],'TEMP':str(scratch),'TMP':str(scratch)}
            before=identities(scratch,env);r['sources']=before;r['compiler_sha256']=q.sha(q.DEFAULT_CC)
            if args.inspect:
                print(json.dumps({k:v for k,v in before.items()if k!='files'},indent=2));return 0
            roms=run.verify_roms(ROOT/'roms/mk2');r['roms']=roms
            seed=profile._read(profile.FACTORY_SEED,factory=True)
            backend=(ROOT/'native/launcher/launcher_backend.cpp').read_text(encoding='utf8')
            for key in ('source_sha256','runtime_sources_sha256','core_overlays_sha256'):
                assert before[key]in backend,'Launcher does not pin these sources: '+key
            exe=scratch/'mk2-native.exe'
            build=q.command([q.DEFAULT_CC,*FLAGS,'-static',*[ROOT/p for p in SOURCES],*LIBRARIES,
                '-Wl,--no-insert-timestamp','-o',exe],scratch,cwd=ROOT,env=env,timeout=240)
            r['native_build']=q.compact(build);assert build['passed'],build['stdout']
            launcher=scratch/'triunit.exe'
            build=q.command([q.DEFAULT_CC,'-std=c++17','-O2','-s','-Wall','-Wextra','-Werror','-static','-municode','-mwindows',
                *[ROOT/'native/launcher'/p for p in ('launcher_main.cpp','launcher_renderer.cpp','launcher_backend.cpp')],
                *['-l'+n for n in ('d3d12','dxgi','d3dcompiler','dxguid','windowscodecs','ole32','uuid','gdi32','user32','shell32','xinput9_1_0')],
                *arguments(ROOT),'-Wl,--no-insert-timestamp','-o',launcher],scratch,cwd=ROOT,env=env,timeout=120)
            r['launcher_build']=q.compact(build);assert build['passed'],build['stdout']
            assert before==identities(scratch,env),'Native source changed during build'
            assert roms==run.verify_roms(ROOT/'roms/mk2')
            product=stage/'product';unlinked(product);product.mkdir(exist_ok=True)
            for rom in run.read_manifest()['roms']:
                target=product/'roms'/rom['path'];unlinked(target);target.parent.mkdir(exist_ok=True)
                if not target.exists():os.link(ROOT/'roms/mk2'/rom['path'],target)
                assert q.sha(target)==rom['sha256']
            video_notice=product/'LICENSE-video.txt'
            unlinked(video_notice);shutil.copy2(ROOT/'native/runtime/LICENSE-video.txt',video_notice)
            for source,target in ((exe,product/'mk2-native.exe'),(launcher,installation_root/'triunit.exe')):
                unlinked(target);shutil.copy2(source,target)
            seed_path=product/'factory-seed.bin';unlinked(seed_path)
            if seed_path.exists():assert seed_path.read_bytes()==seed
            else:seed_path.write_bytes(seed)
            fields=dict(format='1',kind='mk2-native-static-cpp17',readiness='native-playable',
                source='native/mk2/mk2_native_check.cpp',**{k:before[k]for k in ('source_sha256','runtime_sources_sha256','core_overlays_sha256')},
                rom_profile_sha256=q.sha(run.MANIFEST),first_fight_pcs='63906',chunk_request_cycles='2000000',
                cooperative_slack_cycles='2000000',chunk_wall_timeout_ms='10000',bounded_observations='true',
                executable='mk2-native.exe',executable_sha256=q.sha(exe),rom_directory='roms',
                profile_directory='profiles/player',factory_seed='factory-seed.bin')
            manifest=product/'native-package.ini';unlinked(manifest)
            pending=product/'native-package.pending';unlinked(pending)
            pending.write_text(''.join(f'{k}={v}\n'for k,v in fields.items()),encoding='utf8');os.replace(pending,manifest)
            r.update(passed=True,executable=str(product/'mk2-native.exe'),executable_sha256=q.sha(exe),
                launcher_sha256=q.sha(launcher),manifest_sha256=q.sha(manifest))
    except Exception as error:r['error']=repr(error)
    try:
        unlinked(stage)
        if stage.is_dir():
            receipt=stage/'package.json';unlinked(receipt)
            receipt.write_text(json.dumps(r,indent=2)+'\n',encoding='utf8')
    except ValueError as error:r['receipt_not_written']=str(error)
    print(json.dumps({k:v for k,v in r.items()if k not in ('sources','roms')},indent=2));return 0 if r['passed']else 1
if __name__=='__main__':raise SystemExit(main())
