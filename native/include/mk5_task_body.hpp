#pragma once
#include "mk5_irq.hpp"
#include <optional>
#include <memory>
#include "mk5_live_video.hpp"
#include "mk5_protection.hpp"
#include "mk5_sound_status.hpp"

// Shadow: internal to ContinueMain, the widescreen shadow pass changed the next PC (the driver dispatches it again).
enum class TaskBodyStop {DswInput,SoundInput,DiInput,IrqHandler,TemporalBarrier,Untranslated,Budget,MainLoop,DiLimit,DecompressorComplete,TaskEntry,Epoch,Shadow};
// One hardware snapshot of the cabinet inputs for the whole power-on run:
// ports.in01 = IN0|IN1<<16, ports.in2_dsw = IN2|DSW<<16 (DSW also at 01600030h),
// the sound-board status byte, and the declared host raster epoch.
struct Mk5BootInputs {
    BootDiInputs ports{0xffffffffu,0xffffffffu};
    uint8_t sound_status=0xff;
    uint16_t pending=0,next_line=0;
    uint32_t quanta_to_next=0;
    uint32_t instruction_budget=64000000;
};
struct TaskBodyInputs {
    std::optional<uint16_t> dsw,main_dsw;
    // Explicitly frozen host samples for this call, distinct from boot inputs.
    std::optional<uint8_t> sound_status;
    std::optional<BootDiInputs> quiet_di;
    std::optional<BootDiInputs> active_di;
    bool stop_after_decompression=false;
    uint32_t instruction_budget=500000;
};
struct TaskBodyResult {
    TaskBodyStop stop=TaskBodyStop::Untranslated;
    uint32_t pc=0,instruction_count=0,main_loops=0,yields=0,quiet_handlers=0;
    uint64_t reference_cycles=0;
    DswRead16 dsw_read{};
    uint16_t normalized_dsw=0;
    std::vector<BootDiInstruction> instructions;
};
// Fixed translated control graphs (generated by tools/mk1/generate.py from the
// user's program image): power-on graph, first task body and main loop. A
// runner exclusively owns one live CPU/RAM/controller continuation from reset;
// it cannot be copied or reconstructed from a snapshot.
struct Mk5DiagnosticTrim {uint64_t writes=0,returns=0,cmos=0,irqs=0,scanlines=0,dma=0,completions=0;};
class Mk5TaskBodyRunner {
    friend struct Mk5TaskBodyTestAccess;
    const VerifiedMk5Program& p;Mk5MemoryBuffers& m;Mk5IrqController& irq;BootDiState& di;
    Mk5BoardState& f;ResetTrace& s;
    uint32_t expected_pc=0,expected_sp=0,instruction_next=0;uint64_t expected_cycles=0;
    TaskBodyResult result;TaskBodyInputs inputs;Mk5BootInputs boot_inputs;uint32_t remaining=0;
    bool immediate_irq=false,completed=false;
    bool boot_mode=true,booted=false;
    bool main_mode=false,main_started=false;
    // Power-on graph run as a subroutine of the task/main graphs (native_block).
    bool subroutine=false;uint32_t subroutine_sp=0;const uint16_t* dsw_override=nullptr;
    bool boot_graph=false;uint32_t last_pre_pc=0;uint64_t graph_steps=0;
    uint64_t main_di_target=0;
    uint32_t main_di_limit=0;
    std::unique_ptr<Mk5LiveVideo> video;
    bool active_handler=false;
    bool cmos_write_enabled=false;
    // T-Unit video control/DMA palette as last requested, for CPU VRAM access
    // while no Mk5LiveVideo is attached (the live video adopts the same writes).
    bool data_bank=false;uint16_t dma_palette=0;
    Mk5Protection protection;
    Mk5SoundStatus sound_status;
    // Save states (mk5_save_state.hpp): the machine this runner drives (memories, board, DI, IRQ controller, video) and
    // its own value fields. inputs, result and remaining are rewritten by every call; references stay bound.
    template<class A> friend void Fields(A& a,Mk5TaskBodyRunner& r){
        if(!r.video)throw std::logic_error("MK1 save state requires the attached video");
        a(r.m,r.f,r.di,r.irq,r.expected_pc,r.expected_sp,r.instruction_next,r.expected_cycles,r.immediate_irq,r.completed,
          r.boot_mode,r.booted,r.main_mode,r.main_started,r.subroutine,r.subroutine_sp,r.boot_graph,r.last_pre_pc,
          r.graph_steps,r.main_di_target,r.main_di_limit,*r.video,r.active_handler,r.cmos_write_enabled,r.data_bank,
          r.dma_palette,r.protection,r.sound_status);
    }
    // Widescreen shadow pass (mk5_widescreen.hpp, Mk5LiveVideo wide layer), once per built frame after the real walk's first
    // instruction has been counted: with the clip longs widened in a RAM journal, the scenery streamer (unless the game is
    // inside it) and the whole walk run as generated code with no cycles, no interrupt, no instruction count and no hook;
    // only ROM, RAM and the DMA registers are reached (the DMA commands draw the wide layer only). Then the journal and
    // the registers are undone and the real walk runs. Any other access, PC or exception ends the pass as a fault.
    bool shadow=false,shadow_walk=false,shadow_refused=false,resume_walk=false;
    std::vector<std::pair<uint32_t,uint16_t>> shadow_journal;
    std::array<uint32_t,16> shadow_a{};std::array<uint32_t,15> shadow_b{};uint32_t shadow_status=0;
    size_t shadow_returns=0,shadow_writes=0;uint32_t shadow_stack_reads=0,shadow_lowest_sp=0;
    uint64_t shadow_quanta=0,shadow_cycles=0,shadow_steps=0;
    void wide_pre(uint32_t pc);
    void shadow_pre(uint32_t pc);
    void shadow_window(uint32_t pc);
    void shadow_restore();
    void shadow_stop(bool complete);
    void shadow_failed();
    void video_update();
    bool uncounted()const{return subroutine || (active_handler && !main_mode && !boot_mode);}
    void guard()const;
    void pre(uint32_t pc);
    void step(uint32_t pc,uint32_t next,uint32_t cycles);
    // The same for the main loop's shards (tools/mk1/generate.py, layout), which leave by return: true where pre and step
    // throw TaskBodyStop::IrqHandler (an interrupt is entered hundreds of times a frame). interrupt_leave: a shard left so
    // and the driver returns to ContinueMain (not state: it is false outside execute_main).
    bool pre_interrupt(uint32_t pc);
    bool step_interrupt(uint32_t pc,uint32_t next,uint32_t cycles);
    bool interrupt_leave=false;
    bool LeaveForInterrupt(){interrupt_leave=true;return true;}
    void nz(uint32_t value);void z(uint32_t value);
    void load(uint32_t& r,uint32_t v);void add(uint32_t& r,uint32_t v);void sub(uint32_t& r,uint32_t v);
    void compare(uint32_t a,uint32_t b);void shift(uint32_t& r,unsigned n,bool left);
    void sla(uint32_t& r,unsigned n);void rotate(uint32_t& r,unsigned n);void addc(uint32_t& r,uint32_t v);
    void xy(uint32_t& r,uint32_t v,bool subtract);
    uint32_t read(uint32_t pc,uint32_t a,unsigned width,bool sign=true);
    void write(uint32_t pc,uint32_t a,unsigned width,uint32_t v);
    uint32_t port_read(uint32_t pc,uint32_t a,unsigned width);
    uint16_t vram_word(uint32_t a);
    void push(uint32_t pc,uint32_t value);uint32_t pop();unsigned fw(unsigned field)const;
    uint32_t shift_load(uint32_t bit);
    uint32_t pixblt_b_xy(uint32_t pc);
    void native_block(uint32_t pc);
    void dispatch();
    void execute();
    void execute_boot();
    void execute_main();
    // Main-loop graph compiled as shards over PC ranges (tools/mk1/generate.py layout): true when control left the
    // shard (next PC in s.next_original_pc), false when entered at a PC it does not hold.
    template<unsigned K> bool main_shard();
public:
    // Power-on: CPU at the reset vector, CMOS in `state`, controller unstarted.
    Mk5TaskBodyRunner(const VerifiedMk5Program&,Mk5BoardState& state,Mk5MemoryBuffers&,Mk5IrqController&,BootDiState&);
    Mk5TaskBodyRunner(const Mk5TaskBodyRunner&)=delete;
    Mk5TaskBodyRunner& operator=(const Mk5TaskBodyRunner&)=delete;
    // Reset through the first task entry (ffc8bf50): stop TaskEntry, or the
    // first frontier. The raster epoch is started before the first EINT.
    TaskBodyResult Boot(const Mk5BootInputs&);
    TaskBodyResult Run(const TaskBodyInputs&);
    TaskBodyResult ContinueMain(const TaskBodyInputs&,uint32_t new_di_limit);
    void AttachVideo(const VerifiedMk5GlyphBank&,bool remastered=false);
    const Mk5LiveVideo& Video()const{return *video;}
    // Widescreen (Remastered presentation): the shadow pass composes the 512-column frame from now on.
    void EnableWide(){if(!video)throw std::logic_error("MK1 widescreen requires the attached video");video->EnableWide(p.bytes);}
    // Host-only history retention. The live CPU, memory, device state and
    // every continuation remain untouched; qualification keeps full histories.
    Mk5DiagnosticTrim CompactDiagnostics();
};
